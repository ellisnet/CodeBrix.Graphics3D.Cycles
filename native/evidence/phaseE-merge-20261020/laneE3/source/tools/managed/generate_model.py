def pascal(text):
    parts = [p for p in re.split(r'[^A-Za-z0-9]+', text) if p]
    out = ''
    for part in parts:
        if part.isupper() and len(part) > 1 and not any(c.isdigit() for c in part):
            part = part.lower()
        out += part[0].upper() + part[1:]
    if not out:
        out = 'Value'
    if out[0].isdigit():
        out = 'Value' + out
    return out


def xml(text):
    return text.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')


def cs_string(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'


class Model:
    def __init__(self, registry):
        self.registry = registry
        self.types = {t['name']: t for t in registry['nodeTypes']}
        self.children = {}
        for t in registry['nodeTypes']:
            if t['base']:
                self.children.setdefault(t['base'], []).append(t['name'])
        self.class_names = {}
        for name in sorted(self.types):
            self.class_names[name] = CLASS_NAMES.get(name, pascal(name) + 'Node')
        if len(set(self.class_names.values())) != len(self.class_names):
            raise SystemExit('Generated class names collide')

    def ancestors(self, name):
        chain = []
        base = self.types[name]['base']
        while base:
            chain.append(base)
            base = self.types[base]['base']
        return chain

    def category(self, name):
        t = self.types[name]
        if t['kind'] == 1:
            return 'Shader'
        lineage = [name] + self.ancestors(name)
        if LIGHT_ROOT in lineage:
            return 'Light'
        if GEOMETRY_ROOT in lineage:
            return 'Geometry'
        return {'camera': 'Camera', 'film': 'Film', 'integrator': 'Integrator', 'background': 'Background'}.get(
            name, 'Output' if name in OUTPUT_TYPES else 'Scene')

    def folder(self, name):
        return {'Shader': 'Shaders', 'Light': 'Lights', 'Geometry': 'Geometry'}.get(self.category(name), 'Scene')

    def namespace(self, name):
        return f'{ROOT_NAMESPACE}.Generated.{self.folder(name)}'

    def creation(self, name):
        t = self.types[name]
        if name in SINGLETONS:
            return 'Singleton'
        if t['kind'] == 1:
            return 'GraphOutput' if name == 'output' else ('ShaderGraph' if t['hasFactory'] else 'Unavailable')
        return 'Scene' if name in SCENE_CREATABLE else 'Unavailable'

    def base_class(self, name):
        t = self.types[name]
        if t['base']:
            return self.class_names[t['base']]
        return 'ShaderGraphNode' if t['kind'] == 1 else 'CyclesNode'

    def inherited_sockets(self, name):
        names = set()
        for ancestor in self.ancestors(name):
            names.update(s['name'] for s in self.types[ancestor]['inputs'])
        return names

    def inherited_members(self, name):
        members = set()
        for ancestor in self.ancestors(name):
            members.update(self.members(ancestor)[0])
        return members

    def members(self, name):
        """Returns (member names, property list, enum list, input list, output list)."""
        t = self.types[name]
        class_name = self.class_names[name]
        inherited = self.inherited_sockets(name)
        used = set(RESERVED) | {class_name}
        for ancestor in self.ancestors(name):
            used.update(self.members(ancestor)[0])
        own = set()
        props, enums, inputs, outputs = [], [], [], []

        def claim(candidate, suffix):
            member = candidate
            while member in used or member == class_name:
                member += suffix
            used.add(member)
            own.add(member)
            return member

        for socket in t['inputs']:
            if socket['name'] in inherited or socket['flags'] & INTERNAL:
                continue
            kind = socket['type']
            readable = socket['flags'] & READABLE and socket['flags'] & WRITABLE
            if readable and kind != 'closure':
                member = claim(pascal(socket['name']), 'Value')
                enum_name = None
                if kind == 'enum':
                    enum_name = class_name[:-4] + pascal(socket['name']) if class_name.endswith('Node') else class_name + pascal(socket['name'])
                    enums.append((enum_name, socket))
                props.append((member, socket, enum_name))
        if t['kind'] == 1:
            for socket in t['inputs']:
                if socket['name'] in inherited or socket['flags'] & INTERNAL or not socket['flags'] & LINKABLE:
                    continue
                inputs.append((claim(pascal(socket['uiName']) + 'Input', 'Socket'), socket))
            for socket in t['outputs']:
                outputs.append((claim(pascal(socket['uiName']) + 'Output', 'Socket'), socket))
        return own, props, enums, inputs, outputs


def property_code(model, member, socket, enum_name):
    kind = socket['type']
    name = cs_string(socket['name'])
    linkable = ', linkable' if socket['flags'] & LINKABLE else ''
    doc = f"    /// <summary>\n    /// Gets or sets the <c>{xml(socket['name'])}</c> socket ({xml(socket['uiName'])}; native type {kind}{linkable}).\n    /// </summary>\n"
    if kind == 'enum':
        return doc + f'    public {enum_name} {member} {{ get => GetEnum<{enum_name}>({name}); set => SetEnum({name}, value); }}\n'
    if kind == 'node':
        target = model.class_names.get(socket['nodeType'], 'CyclesNode') if socket['nodeType'] else 'CyclesNode'
        return doc + f'    public {target} {member} {{ get => GetNode<{target}>({name}); set => SetNode({name}, value); }}\n'
    if kind == 'array_node':
        target = model.class_names.get(socket['nodeType'], 'CyclesNode') if socket['nodeType'] else 'CyclesNode'
        return doc + f'    public {target}[] {member} {{ get => GetNodeArray<{target}>({name}); set => SetNodeArray({name}, value); }}\n'
    if kind in SCALAR:
        cs, accessor = SCALAR[kind]
        return doc + f'    public {cs} {member} {{ get => Get{accessor}({name}); set => Set{accessor}({name}, value); }}\n'
    if kind in ARRAY_ELEMENT:
        element = ARRAY_ELEMENT[kind]
        accessor = ARRAY_ACCESSOR[element]
        return doc + f'    public {element}[] {member} {{ get => Get{accessor}({name}); set => Set{accessor}({name}, value); }}\n'
    raise SystemExit(f'Unhandled socket type {kind} ({socket["name"]})')


def enum_code(enum_name, node_name, socket):
    lines = [f"/// <summary>\n/// The items of the <c>{xml(socket['name'])}</c> enumeration socket of the native <c>{xml(node_name)}</c> node type.\n/// The values are the native enumeration values.\n/// </summary>\n",
             f'public enum {enum_name}\n{{\n']
    used = set()
    entries = []
    for entry in socket['enumValues']:
        member = pascal(entry['name'])
        while member in used:
            member += '_'
        used.add(member)
        entries.append(f"    /// <summary>The native <c>{xml(entry['name'])}</c> item.</summary>\n    {member} = {entry['value']}")
    lines.append(',\n\n'.join(entries) + '\n}\n')
    return ''.join(lines)


def class_code(model, name):
    t = model.types[name]
    cls = model.class_names[name]
    _, props, enums, inputs, outputs = model.members(name)
    category = model.category(name)
    creation = model.creation(name)
    abstract = not t['hasFactory'] and t['kind'] == 0
    sealed = not abstract and name not in model.children
    modifier = 'abstract ' if abstract else ('sealed ' if sealed else '')
    base = model.base_class(name)
    shader = t['kind'] == 1
    extras = EXTRAS.get(name, '')
    if extras == 'IMAGE':
        extras = IMAGE_EXTRA
    text = ''
    creation_note = {
        'Singleton': f'Get the scene\'s instance from <see cref="CyclesScene"/>.',
        'Scene': 'Create it with <see cref="CyclesScene.Create{T}"/> or a typed CyclesScene factory.',
        'ShaderGraph': 'Add it to a shader graph with <see cref="ShaderNode.Add{T}"/>.',
        'GraphOutput': 'Every shader graph owns exactly one; get it from <see cref="ShaderNode.Output"/>.',
        'Unavailable': 'The current native host ABI does not create this type directly; it is described for completeness and as a base type.',
    }[creation]
    text += (f'/// <summary>\n/// The native <c>{xml(name)}</c> node type ({category.lower()} category). {creation_note}\n/// </summary>\n'
             f'public {modifier}partial class {cls} : {base}\n{{\n')
    text += f'    /// <summary>\n    /// The native registry type name, <c>{xml(name)}</c>.\n    /// </summary>\n    public {"new " if t["base"] else ""}const string NativeTypeName = {cs_string(name)};\n\n'
    if shader:
        text += f'    internal {cls}(CyclesScene scene, Node handle, ShaderNode graph) : base(scene, handle, graph)\n    {{\n    }}\n'
    else:
        text += f'    internal {cls}(CyclesScene scene, Node handle) : base(scene, handle)\n    {{\n    }}\n'
    for member, socket, enum_name in props:
        text += '\n' + property_code(model, member, socket, enum_name)
    for member, socket in inputs:
        text += (f"\n    /// <summary>\n    /// Gets the <c>{xml(socket['uiName'])}</c> input socket ({socket['type']}), the target of a graph link.\n    /// </summary>\n"
                 f"    public ShaderInput {member} => new(this, {cs_string(socket['uiName'])});\n")
    for member, socket in outputs:
        text += (f"\n    /// <summary>\n    /// Gets the <c>{xml(socket['uiName'])}</c> output socket ({socket['type']}), the source of a graph link.\n    /// </summary>\n"
                 f"    public ShaderOutput {member} => new(this, {cs_string(socket['uiName'])});\n")
    text += extras
    text += '}\n'
    for enum_name, socket in enums:
        text += '\n' + enum_code(enum_name, name, socket)
    usings = ['System']
    if re.search(r'\bVector[23]\b', text):
        usings.append('System.Numerics')
    if 'MemoryMarshal' in text:
        usings.append('System.Runtime.InteropServices')
    others = {model.namespace(other) for other in model.types} | {ROOT_NAMESPACE + '.Nodes'}
    usings += sorted(ns for ns in others if ns != model.namespace(name))
    return (HEADER + BANNER + '\n' + ''.join(f'using {u};\n' for u in usings)
            + f'\nnamespace {model.namespace(name)};\n\n' + text)


def catalogue_code(model):
    usings = ['System', 'System.Collections.Generic']
    usings += sorted({model.namespace(n) for n in model.types} | {ROOT_NAMESPACE + '.Nodes'})
    text = HEADER + BANNER + '\n' + ''.join(f'using {u};\n' for u in usings) + f'\nnamespace {ROOT_NAMESPACE}.Generated;\n\n'
    text += ('/// <summary>\n/// The catalogue of every native node type in the registry the typed model was generated from:\n'
             '/// its category, how it is created, its generated class and its input and output sockets.\n/// </summary>\n'
             'public static class NodeType\n{\n')
    text += f"    /// <summary>\n    /// The registry ABI version the catalogue was generated from.\n    /// </summary>\n    public const uint RegistryAbiVersion = {model.registry['abiVersion']};\n\n"
    text += ('    /// <summary>\n    /// Gets every registered node type, ordered by native name.\n    /// </summary>\n'
             '    public static IReadOnlyList<NodeTypeInfo> All { get; } = Build();\n\n'
             '    private static readonly Dictionary<string, NodeTypeInfo> ByName = Index(info => info.Name);\n\n'
             '    private static readonly Dictionary<Type, NodeTypeInfo> ByType = Index(info => info.ClrType);\n\n'
             '    /// <summary>\n    /// Finds a node type by its native name.\n    /// </summary>\n'
             '    /// <param name="name">The native type name, for example <c>diffuse_bsdf</c>.</param>\n'
             '    /// <returns>The node type, or <see langword="null"/> when the registry has no such type.</returns>\n'
             '    public static NodeTypeInfo Find(string name) => name != null && ByName.TryGetValue(name, out NodeTypeInfo info) ? info : null;\n\n'
             '    /// <summary>\n    /// Finds the node type a generated class represents.\n    /// </summary>\n'
             '    /// <param name="type">The generated class.</param>\n'
             '    /// <returns>The node type, or <see langword="null"/> when <paramref name="type"/> is not a generated node class.</returns>\n'
             '    public static NodeTypeInfo Of(Type type) => type != null && ByType.TryGetValue(type, out NodeTypeInfo info) ? info : null;\n\n'
             '    /// <summary>\n    /// Finds the node type a generated class represents.\n    /// </summary>\n'
             '    /// <typeparam name="T">The generated class.</typeparam>\n'
             '    /// <returns>The node type.</returns>\n'
             '    public static NodeTypeInfo Of<T>() where T : CyclesNode => Of(typeof(T));\n\n'
             '    private static Dictionary<TKey, NodeTypeInfo> Index<TKey>(Func<NodeTypeInfo, TKey> key)\n    {\n'
             '        Dictionary<TKey, NodeTypeInfo> index = [];\n'
             '        foreach (NodeTypeInfo info in All) index.Add(key(info), info);\n'
             '        return index;\n    }\n\n')
    text += '    private static NodeTypeInfo[] Build() =>\n    [\n'

    def socket(s):
        enums = ', '.join(f'new EnumEntry({cs_string(e["name"])}, {e["value"]})' for e in s['enumValues'])
        node_type = cs_string(s['nodeType']) if s['nodeType'] else 'null'
        return (f'new SocketInfo({cs_string(s["name"])}, {cs_string(s["uiName"])}, {cs_string(s["type"])}, '
                f'ValueKind.{VALUE_KIND[s["valueType"]]}, {s["components"]}u, (PropertyFlags){s["flags"]}, {node_type}, [{enums}])')
    entries = []
    for name in sorted(model.types):
        t = model.types[name]
        cls = model.class_names[name]
        creation = model.creation(name)
        abstract = not t['hasFactory'] and t['kind'] == 0
        if abstract:
            factory = 'null'
        elif t['kind'] == 1:
            factory = f'static (scene, handle, graph) => new {cls}(scene, handle, graph)'
        else:
            factory = f'static (scene, handle, graph) => new {cls}(scene, handle)'
        base = cs_string(t['base']) if t['base'] else 'null'
        inputs = ',\n            '.join(socket(s) for s in t['inputs'])
        outputs = ',\n            '.join(socket(s) for s in t['outputs'])
        entries.append(
            f'        new NodeTypeInfo({cs_string(name)}, NodeCategory.{model.category(name)}, NodeCreation.{creation}, {base}, '
            f'{"true" if t["hasFactory"] else "false"}, typeof({cls}), {factory},\n'
            f'            [{inputs}],\n            [{outputs}])')
    text += ',\n'.join(entries) + '\n    ];\n}\n'
    return text


def render(registry):
    model = Model(registry)
    files = {}
    for name in sorted(model.types):
        files[f'{model.folder(name)}/{model.class_names[name]}.cs'] = class_code(model, name)
    files['NodeType.cs'] = catalogue_code(model)
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--registry', type=Path, default=REGISTRY, help='registry JSON to read')
    parser.add_argument('--update-registry', action='store_true', help='copy --registry over Generated/registry.json first')
    parser.add_argument('--check', action='store_true', help='verify the checked-in output instead of writing it')
    args = parser.parse_args()
    source = args.registry.read_text(encoding='utf-8')
    registry = json.loads(source)
    if args.update_registry and args.registry.resolve() != REGISTRY.resolve():
        REGISTRY.write_text(json.dumps(registry, indent=1, ensure_ascii=False) + '\n', encoding='utf-8')
    files = render(registry)
    existing = {p.relative_to(GENERATED).as_posix() for p in GENERATED.rglob('*.cs')}
    if args.check:
        stale = sorted(path for path, text in files.items()
                       if not (GENERATED / path).exists() or (GENERATED / path).read_text(encoding='utf-8') != text)
        extra = sorted(existing - set(files))
        if stale or extra:
            print(json.dumps({'upToDate': False, 'stale': stale, 'unexpected': extra}, indent=1))
            return 1
        print(json.dumps({'upToDate': True, 'files': len(files)}))
        return 0
    for path in sorted(existing - set(files)):
        (GENERATED / path).unlink()
    for path, text in files.items():
        target = GENERATED / path
        target.parent.mkdir(parents=True, exist_ok=True)
        if not target.exists() or target.read_text(encoding='utf-8') != text:
            target.write_text(text, encoding='utf-8')
    print(json.dumps({'generated': len(files), 'nodeTypes': len(registry['nodeTypes'])}))
    return 0


if __name__ == '__main__':
    sys.exit(main())
