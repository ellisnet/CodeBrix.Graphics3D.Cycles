"""Generate the typed Cycles node model from the native registry JSON.

Input:  src/CodeBrix.Graphics3D.Cycles/Generated/registry.json, the output of
        cbc_host_registry_json (CyclesHost.RegistryJson()) captured from the
        native host built in this repository.
Output: src/CodeBrix.Graphics3D.Cycles/Generated/<Folder>/<Class>.cs, one class per
        registered node type (with its enums), and Generated/NodeType.cs, the
        catalogue of every node type and socket.

    python3 tools/managed/generate_model.py            # regenerate
    python3 tools/managed/generate_model.py --check    # fail when out of date
    python3 tools/managed/generate_model.py --registry native/work/d2/registry.json --update-registry

The generator is deterministic; its output is checked in and must build with
zero warnings under the repository's family rules.
"""
