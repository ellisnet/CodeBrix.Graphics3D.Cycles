"""Merge wave 6 part 2: append the generated per-device tables (device_tables.py output for samsung, hp, s20) to native/DEVICE.md as one
new section. No other text of DEVICE.md is touched; the section contains tool output plus one provenance sentence. Run once, after all device runs
(DEVICE.md is a hashed input of the gates)."""
import subprocess, sys
from pathlib import Path
R = Path('/home/jeremy/GitHome/CodeBrix.Graphics3D.Cycles'); M = R/'native/work/merge6'; p = R/'native/DEVICE.md'; t = p.read_text()
assert '## Merge wave 6: device tables' not in t, 'already applied'
tables = subprocess.run([sys.executable, str(M/'tools/device_tables.py'), 'samsung', 'hp', 's20'], check=True, capture_output=True, text=True).stdout
(M/'device/device-tables.md').write_text(tables)
head = ("## Merge wave 6: device tables\n\n"
        "Generated by `native/work/merge6/tools/device_tables.py` from each run's `results.json` (merge wave 6, part 2; the runs are frozen in "
        "`native/evidence/merge-20261023b/merge6/runs/<device>/`). Wall times are device seconds per job; \"Judged against\" names the reference the "
        "result was judged against (glibc device-scene flow, the device's own CPU, or the source capture's CPU film).\n")
p.write_text(t.rstrip('\n')+'\n\n'+head+tables.rstrip('\n')+'\n')
print('DEVICE.md updated; tables', len(tables), 'bytes')
