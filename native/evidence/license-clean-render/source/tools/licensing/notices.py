"""Generate root attribution files from the reviewed dependency manifest."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def generate(check=False):
    manifest = json.loads((ROOT/'third_party/dependencies.json').read_text())
    header = ('CodeBrix.Graphics3D.Cycles\n'
              'Copyright (c) 2026 Jeremy Ellis and contributors\n'
              'Original contributions: Apache-2.0; see LICENSE.\n\n'
              'Third-party code retains its original licenses and notices.\n'
              'Generated by tools/licensing/notices.py from third_party/dependencies.json.\n'
              'This inventory covers current source, native development builds and test tools.\n'
              'It does not certify unbuilt RIDs or a future NuGet payload.\n\n')
    notice = header
    full = header + manifest['scope'] + '\n\n'
    files = []
    for c in manifest['components']:
        block = (c['name'] + ' ' + c['version'] + '\n'
                 + 'Origin: ' + c['source'] + '\n'
                 + 'Selected license: ' + c['license'] + '\n'
                 + 'Use: ' + c['use'] + '\n'
                 + 'Attribution: ' + c['attribution'] + '\n')
        if c.get('revision'):
            block += 'Pinned revision: ' + c['revision'] + '\n'
        if c.get('conditions'):
            block += 'Conditions: ' + c['conditions'] + '\n'
        if c.get('embeddedLicenseForms'):
            block += 'Retained file/license forms: ' + '; '.join(c['embeddedLicenseForms']) + '\n'
        notice += block + '\n'
        full += block + 'Notices: ' + ', '.join(c['notices']) + '\n\n'
        files += c['notices']
    full += 'FULL LICENSE AND ATTRIBUTION TEXTS\n' + '=' * 70 + '\n'
    for name in dict.fromkeys(files):
        path = ROOT/name
        expected = manifest['noticeSha256'][name]
        if hashlib.sha256(path.read_bytes()).hexdigest() != expected:
            raise RuntimeError('License/attribution text changed without review: ' + name)
        full += '\n' + '=' * 70 + '\n' + name + '\n' + '=' * 70 + '\n\n'
        full += path.read_text().rstrip() + '\n'
    for name, content in [('NOTICE',notice),('THIRD-PARTY-NOTICES.txt',full)]:
        path = ROOT/name
        if check:
            if not path.exists() or path.read_text() != content:
                raise RuntimeError('Stale generated notices: ' + name)
        else:
            path.write_text(content)
    return len(manifest['components'])


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check',action='store_true')
    print(generate(parser.parse_args().check),'reviewed components')
